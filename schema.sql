
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Giocatore',
  role text not null default 'player' check (role in ('player','admin')),
  total_points integer not null default 0
);

create table public.matches (
  id bigint generated by default as identity primary key,
  competition text not null,
  home_team text not null,
  away_team text not null,
  deadline timestamptz,
  result_home integer,
  result_away integer
);

create table public.predictions (
  id bigint generated by default as identity primary key,
  match_id bigint not null references public.matches(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  home_score integer not null,
  away_score integer not null,
  points integer not null default 0,
  unique(match_id,user_id)
);

alter table public.profiles enable row level security;
alter table public.matches enable row level security;
alter table public.predictions enable row level security;

create or replace function public.is_admin()
returns boolean language sql stable security definer
set search_path=public
as $$
  select exists (
    select 1 from public.profiles
    where id=auth.uid() and role='admin'
  );
$$;

create or replace function public.handle_new_user()
returns trigger language plpgsql security definer
set search_path=public
as $$
begin
  insert into public.profiles(id,display_name)
  values(new.id,coalesce(new.raw_user_meta_data->>'display_name','Giocatore'));
  return new;
end;
$$;

create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

create policy "profiles read" on public.profiles
for select to authenticated using (true);

create policy "profiles update" on public.profiles
for update to authenticated
using (id=auth.uid() or public.is_admin())
with check (id=auth.uid() or public.is_admin());

create policy "matches read" on public.matches
for select to authenticated using (true);

create policy "admin manages matches" on public.matches
for all to authenticated
using (public.is_admin()) with check (public.is_admin());

create policy "predictions read" on public.predictions
for select to authenticated
using (
  user_id=auth.uid() or public.is_admin() or
  exists (
    select 1 from public.matches m
    where m.id=match_id and m.deadline is not null and now()>=m.deadline
  )
);

create policy "predictions insert" on public.predictions
for insert to authenticated
with check (
  user_id=auth.uid() and exists (
    select 1 from public.matches m
    where m.id=match_id and (m.deadline is null or now()<m.deadline)
  )
);

create policy "predictions update" on public.predictions
for update to authenticated
using (user_id=auth.uid() or public.is_admin())
with check (user_id=auth.uid() or public.is_admin());
